//! Embeds every `i18n/<locale>/nira.ftl` into the binary as
//! `OUT_DIR/i18n_catalog.rs`, so translations need no files at runtime.

use std::fs;
use std::path::Path;

fn main() {
    let dir = Path::new(env!("CARGO_MANIFEST_DIR")).join("../../i18n");
    println!("cargo:rerun-if-changed={}", dir.display());
    let mut locales: Vec<(String, String)> = Vec::new();
    for entry in fs::read_dir(&dir).expect("i18n dir").flatten() {
        let ftl = entry.path().join("nira.ftl");
        if ftl.is_file() {
            println!("cargo:rerun-if-changed={}", ftl.display());
            let locale = entry.file_name().to_string_lossy().into_owned();
            let abs = ftl.canonicalize().expect("canonical ftl path");
            locales.push((locale, abs.to_string_lossy().into_owned()));
        }
    }
    locales.sort();

    let mut out = String::from("// @generated by build.rs; do not edit.\n");
    out.push_str("pub const CATALOG: &[(&str, &str)] = &[\n");
    for (locale, path) in &locales {
        out.push_str(&format!("    ({locale:?}, include_str!({path:?})),\n"));
    }
    out.push_str("];\n");
    let dest = Path::new(&std::env::var("OUT_DIR").unwrap()).join("i18n_catalog.rs");
    fs::write(dest, out).expect("write i18n catalog");
}
